def do(path, marker, anchor, add, tag):
    t = io.open(path, encoding='utf-8').read()
    if marker in t:
        print('⚠ %s 已有目标段（幂等），跳过' % tag)
        return
    if anchor not in t:
        raise SystemExit('✗ %s 锚点不存在：%r' % (tag, anchor[:30]))
    if not t.rstrip(NL).endswith(anchor):
        raise SystemExit('✗ %s 锚点不在文件末尾（尾部另有内容，需人工确认）' % tag)
    t2 = t.rstrip(NL) + add
    io.open(path, 'w', encoding='utf-8', newline=NL).write(t2)
    r = io.open(path, encoding='utf-8').read()
    if marker not in r:
        raise SystemExit('✗ %s 写盘后仍无目标段' % tag)
    print('✔ %s：%d → %d 字符' % (tag, len(t), len(r)))


